// Build-time import of the measurements in ../results (see results/README.md):
//
//   results/machines.json   -> src/generated/results.ts  (the machines the runs name)
//   results/runs/*.json     -> src/generated/results.ts  (every run, as written)
//   results/editions/*.json -> src/generated/results.ts  (Ollaya Bench editions: which runs, the score)
//
// The results page (src/pages/results.tsx) draws its charts from these, and the build also
// publishes each file unchanged under /results/ for download.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const results = join(root, '..', 'results')
const outDir = join(root, 'src', 'generated')

const machines = JSON.parse(await readFile(join(results, 'machines.json'), 'utf8'))
const files = (await readdir(join(results, 'runs'))).filter((f) => f.endsWith('.json')).sort()
const runs = []
for (const file of files) {
  const run = JSON.parse(await readFile(join(results, 'runs', file), 'utf8'))
  if (run.schema !== 1) throw new Error(`results/runs/${file}: unknown schema ${run.schema}`)
  if (run.machine && !machines[run.machine]) throw new Error(`results/runs/${file}: unknown machine ${run.machine}`)
  runs.push({ file, ...run })
}

const editions = []
const editionDir = join(results, 'editions')
const editionFiles = (await readdir(editionDir).catch(() => [])).filter((f) => f.endsWith('.json')).sort()
for (const file of editionFiles) {
  const edition = JSON.parse(await readFile(join(editionDir, file), 'utf8'))
  if (edition.schema !== 1) throw new Error(`results/editions/${file}: unknown schema ${edition.schema}`)
  for (const run of edition.runs) if (!files.includes(run)) throw new Error(`results/editions/${file}: no run ${run}`)
  editions.push(edition)
}

const header = '// AUTO-GENERATED by scripts/gen-results.mjs from ../results; do not edit. Run `npm run gen`.\n\n'
await mkdir(outDir, { recursive: true })
await writeFile(
  join(outDir, 'results.ts'),
  header +
    `export const machinesRaw: unknown = ${JSON.stringify(machines, null, 1)}\n\n` +
    `export const runsRaw: unknown[] = ${JSON.stringify(runs, null, 1)}\n\n` +
    `export const editionsRaw: unknown[] = ${JSON.stringify(editions, null, 1)}\n`,
)
console.log(`results: ${Object.keys(machines).length} machines, ${runs.length} runs, ${editions.length} editions`)
